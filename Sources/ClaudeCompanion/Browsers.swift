import AppKit

/// A browser (and, for Chromium browsers, a profile) to open Claude's sign-in page in.
/// Claude Code opens links with $BROWSER, so each account can sign in with the right identity.
struct LoginBrowser: Identifiable, Hashable {
    /// "app:<bundle id>" or "chromium:<bundle id>:<profile directory>".
    let id: String
    let label: String
    let appPath: String
    let profileDirectory: String?

    /// Chromium browsers keep their profiles in "<Application Support>/<folder>/Local State".
    private static let chromium: [(name: String, bundleID: String, folder: String)] = [
        ("Chrome", "com.google.Chrome", "Google/Chrome"),
        ("Chrome Beta", "com.google.Chrome.beta", "Google/Chrome Beta"),
        ("Brave", "com.brave.Browser", "BraveSoftware/Brave-Browser"),
        ("Edge", "com.microsoft.edgemac", "Microsoft Edge"),
        ("Vivaldi", "com.vivaldi.Vivaldi", "Vivaldi"),
        ("Opera", "com.operasoftware.Opera", "com.operasoftware.Opera"),
    ]
    private static let plain: [(name: String, bundleID: String)] = [
        ("Safari", "com.apple.Safari"), ("Firefox", "org.mozilla.firefox"), ("Arc", "company.thebrowser.Browser"),
    ]

    /// Every installed browser, with one entry per Chromium profile.
    static func available() -> [LoginBrowser] {
        var result: [LoginBrowser] = []
        for b in chromium {
            guard let app = NSWorkspace.shared.urlForApplication(withBundleIdentifier: b.bundleID) else { continue }
            let state = Paths.home + "/Library/Application Support/\(b.folder)/Local State"
            let cache = (try? JSONSerialization.jsonObject(with: Data(contentsOf: URL(fileURLWithPath: state))))
                .flatMap { $0 as? [String: Any] }
                .flatMap { $0["profile"] as? [String: Any] }
                .flatMap { $0["info_cache"] as? [String: [String: Any]] } ?? [:]
            if cache.isEmpty {
                result.append(LoginBrowser(id: "app:\(b.bundleID)", label: b.name, appPath: app.path, profileDirectory: nil))
            }
            for (dir, info) in cache.sorted(by: { $0.key.localizedStandardCompare($1.key) == .orderedAscending }) {
                let name = info["name"] as? String ?? dir
                let email = (info["user_name"] as? String).flatMap { $0.isEmpty ? nil : $0 }
                result.append(LoginBrowser(id: "chromium:\(b.bundleID):\(dir)",
                                           label: "\(b.name) — \(name)" + (email.map { " (\($0))" } ?? ""),
                                           appPath: app.path, profileDirectory: dir))
            }
        }
        for b in plain {
            guard let app = NSWorkspace.shared.urlForApplication(withBundleIdentifier: b.bundleID) else { continue }
            result.append(LoginBrowser(id: "app:\(b.bundleID)", label: b.name, appPath: app.path, profileDirectory: nil))
        }
        return result
    }

    static func find(_ id: String?) -> LoginBrowser? {
        guard let id else { return nil }
        return available().first { $0.id == id }
    }

    /// The small script set as $BROWSER: Claude Code calls it with the sign-in URL.
    var script: String {
        func q(_ s: String) -> String { "'" + s.replacingOccurrences(of: "'", with: "'\\''") + "'" }
        if let profileDirectory {
            return "#!/bin/sh\n# Generated by Claude Companion: opens links in \(label.replacingOccurrences(of: "\n", with: " ")).\nexec open -na \(q(appPath)) --args --profile-directory=\(q(profileDirectory)) \"$1\"\n"
        }
        return "#!/bin/sh\n# Generated by Claude Companion: opens links in \(label.replacingOccurrences(of: "\n", with: " ")).\nexec open -a \(q(appPath)) \"$1\"\n"
    }
}
