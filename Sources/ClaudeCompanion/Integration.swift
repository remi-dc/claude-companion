import AppKit
import Foundation

enum IntegrationError: LocalizedError {
    case invalidSettings(String)
    var errorDescription: String? {
        switch self {
        case .invalidSettings(let p): return "\(p) is not valid JSON — left untouched."
        }
    }
}

enum Integration {
    static let marker = "claude-companion-hook"

    // MARK: Hook shim

    /// A stable path that settings.json can point at. Rewritten on each launch so moving
    /// the .app never breaks hooks.
    static func writeHookShim() {
        guard let exe = Bundle.main.executablePath else { return }
        Paths.ensureDir(Paths.binDir)
        let script = """
        #!/bin/sh
        # Generated by Claude Companion. Forwards Claude Code hooks to the app.
        # Runs in the background so Claude never waits on it.
        touch "$HOME/.claude-companion/last-activity" 2>/dev/null
        input=$(cat)
        printf '%s' "$input" | CLAUDE_COMPANION_PPID=$PPID "\(exe)" hook "$@" >/dev/null 2>&1 &
        exit 0
        """
        writeExecutable(script, to: Paths.hookShim)
    }

    // MARK: settings.json hooks

    static func hooksInstalled(for account: Account) -> Bool {
        guard let data = FileManager.default.contents(atPath: account.settingsPath),
              let s = String(data: data, encoding: .utf8) else { return false }
        return s.contains(marker)
    }

    /// Installed by the current version (includes the prompt hook that drives the "working" state).
    static func hooksUpToDate(for account: Account) -> Bool {
        guard let data = FileManager.default.contents(atPath: account.settingsPath),
              let s = String(data: data, encoding: .utf8) else { return false }
        return s.contains(marker) && s.contains(" prompt --account \(account.id)")
            && s.contains(" tool --account \(account.id)")
            && s.contains(" tool-start --account \(account.id)")
    }

    static func installHooks(for account: Account) throws {
        try editSettings(account) { hooks in
            let cmd = { (kind: String) in "\"\(Paths.hookShim)\" \(kind) --account \(account.id)" }
            func entry(_ kind: String, matcher: String? = nil) -> [String: Any] {
                var e: [String: Any] = ["hooks": [["type": "command", "command": cmd(kind), "timeout": 10]]]
                if let matcher { e["matcher"] = matcher }
                return e
            }
            hooks["Stop", default: [Any]()].append(entry("stop"))
            hooks["UserPromptSubmit", default: [Any]()].append(entry("prompt"))
            hooks["PostToolUse", default: [Any]()].append(entry("tool"))
            hooks["PreToolUse", default: [Any]()].append(entry("tool-start"))
            hooks["Notification", default: [Any]()].append(entry("notification", matcher: ""))
        }
    }

    static func removeHooks(for account: Account) throws {
        try editSettings(account) { _ in }
    }

    /// Loads settings.json, strips any previous Companion hooks, lets `mutate` add new ones,
    /// and writes it back (with a one-time backup). Other settings and hooks are preserved.
    private static func editSettings(_ account: Account, mutate: (inout [String: [Any]]) -> Void) throws {
        let fm = FileManager.default
        Paths.ensureDir(account.expandedConfigDir)
        var root: [String: Any] = [:]
        if let data = fm.contents(atPath: account.settingsPath), !data.isEmpty {
            guard let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else {
                throw IntegrationError.invalidSettings(account.settingsPath)
            }
            root = obj
            let backup = account.settingsPath + ".companion-backup"
            if !fm.fileExists(atPath: backup) { try? data.write(to: URL(fileURLWithPath: backup)) }
        }

        var hooks: [String: [Any]] = [:]
        for (event, value) in (root["hooks"] as? [String: Any]) ?? [:] {
            guard let groups = value as? [Any] else { hooks[event] = []; continue }
            hooks[event] = groups.filter { group in
                guard let g = group as? [String: Any], let hs = g["hooks"] as? [[String: Any]] else { return true }
                return !hs.contains { ($0["command"] as? String)?.contains(marker) == true }
            }
        }
        mutate(&hooks)
        hooks = hooks.filter { !$0.value.isEmpty }
        if hooks.isEmpty { root.removeValue(forKey: "hooks") } else { root["hooks"] = hooks }

        let out = try JSONSerialization.data(withJSONObject: root, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes])
        try out.write(to: URL(fileURLWithPath: account.settingsPath), options: .atomic)
    }

    // MARK: Account switching

    static func writeActiveFile(_ account: Account) {
        Paths.ensureDir(Paths.companionDir)
        try? account.expandedConfigDir.write(toFile: Paths.activeFile, atomically: true, encoding: .utf8)
        // The wrappers read this to set $BROWSER, so /login opens the right browser profile.
        try? (browserScript(for: account) ?? "").write(toFile: activeBrowserFile, atomically: true, encoding: .utf8)
    }

    static let activeBrowserFile = Paths.companionDir + "/active-browser"

    /// Files the wrappers read: accounts (for the reminder), folder rules, and the reminder delay.
    /// Tab-separated, one entry per line.
    static func writeWrapperData(_ config: CompanionConfig) {
        Paths.ensureDir(Paths.companionDir)
        func clean(_ s: String) -> String { s.replacingOccurrences(of: "\t", with: " ").replacingOccurrences(of: "\n", with: " ") }
        let accounts = config.accounts.map { a in
            // "-" marks an empty field: the shell collapses consecutive tabs, which would shift columns.
            [clean(a.name), a.expandedConfigDir, browserScript(for: a) ?? "-", clean(a.loggedInEmail ?? "-")].joined(separator: "\t")
        }
        let rules = config.folderRules.compactMap { r -> String? in
            guard let a = config.account(r.accountID) else { return nil }
            return [r.expandedFolder, a.expandedConfigDir, browserScript(for: a) ?? "-"].joined(separator: "\t")
        }
        try? (accounts.joined(separator: "\n") + "\n").write(toFile: Paths.companionDir + "/accounts", atomically: true, encoding: .utf8)
        try? (rules.joined(separator: "\n") + (rules.isEmpty ? "" : "\n")).write(toFile: Paths.companionDir + "/rules", atomically: true, encoding: .utf8)
        try? "\(config.reminderHours)".write(toFile: Paths.companionDir + "/reminder-hours", atomically: true, encoding: .utf8)
    }

    /// Shell shared by both wrappers: sets DIR/B/RULE from folder rules, else the active account.
    private static let chooseAccountShell = #"""
    CC="$HOME/.claude-companion"
    TAB=$(printf '\t')
    DIR=""; B=""; RULE=""
    # 1. Folder rules: the longest folder containing the current directory wins.
    if [ -f "$CC/rules" ]; then
      best=0
      while IFS="$TAB" read -r folder dir browser || [ -n "$folder" ]; do
        [ -z "$folder" ] && continue
        case "$PWD/" in
          "$folder"/*) if [ ${#folder} -gt $best ]; then best=${#folder}; DIR="$dir"; B="$browser"; RULE="$folder"; fi ;;
        esac
      done < "$CC/rules"
    fi
    # 2. Otherwise the account picked in the menu bar.
    if [ -z "$RULE" ]; then
      [ -f "$CC/active-config-dir" ] && DIR=$(cat "$CC/active-config-dir")
      [ -f "$CC/active-browser" ] && B=$(cat "$CC/active-browser")
    fi
    """#

    private static let applyAccountShell = #"""
    [ "$B" = "-" ] && B=""
    if [ -n "$DIR" ] && [ "$DIR" != "$HOME/.claude" ]; then export CLAUDE_CONFIG_DIR="$DIR"; fi
    if [ -z "$BROWSER" ] && [ -n "$B" ] && [ -x "$B" ]; then export BROWSER="$B"; fi
    """#

    /// After a long break, confirm the account in the terminal (one key press; Enter keeps it).
    private static let reminderShell = #"""
    remind() {
      [ -n "$RULE" ] && return 0
      [ -t 0 ] && [ -t 1 ] || return 0
      for a in "$@"; do case "$a" in -p|--print|-v|--version|-h|--help) return 0 ;; esac; done
      case "$1" in mcp|config|update|doctor|install|setup-token|migrate-installer|api-key|plugin|auth) return 0 ;; esac
      H=$(cat "$CC/reminder-hours" 2>/dev/null)
      case "$H" in ''|0|*[!0-9]*) return 0 ;; esac
      [ -f "$CC/accounts" ] || return 0
      LAST=$(stat -f %m "$CC/last-activity" 2>/dev/null || echo 0)
      NOW=$(date +%s)
      [ $((NOW - LAST)) -lt $((H * 3600)) ] && return 0
      NAME=""; EMAIL=""; MENU=""; i=0
      while IFS="$TAB" read -r name dir browser email || [ -n "$name" ]; do
        [ -z "$name" ] && continue
        i=$((i + 1))
        MENU="$MENU  $i $name"
        if [ "$dir" = "$DIR" ]; then NAME="$name"; EMAIL="$email"; [ "$EMAIL" = "-" ] && EMAIL=""; fi
      done < "$CC/accounts"
      [ -z "$NAME" ] && return 0
      [ -n "$EMAIL" ] && EMAIL=" ($EMAIL)"
      printf '\n  \033[1;38;5;209m▸ Claude Companion\033[0m  It has been a while. Starting on \033[1m%s\033[0m%s\n' "$NAME" "$EMAIL"
      printf '  Enter keeps it, or press a number to use another account for this session:%s  ' "$MENU"
      OLD=$(stty -g); stty -icanon -echo min 1 time 0; KEY=$(dd bs=1 count=1 2>/dev/null); stty "$OLD"
      case "$KEY" in
        [1-9])
          j=0
          while IFS="$TAB" read -r name dir browser email || [ -n "$name" ]; do
            [ -z "$name" ] && continue
            j=$((j + 1))
            if [ "$j" = "$KEY" ]; then DIR="$dir"; B="$browser"; NAME="$name"; fi
          done < "$CC/accounts" ;;
      esac
      printf '→ %s\n\n' "$NAME"
      touch "$CC/last-activity"
    }
    """#

    /// Writes the account's $BROWSER script and returns its path (nil = system default browser).
    @discardableResult
    static func browserScript(for account: Account) -> String? {
        guard let browser = LoginBrowser.find(account.loginBrowser) else { return nil }
        Paths.ensureDir(Paths.binDir)
        let path = Paths.binDir + "/browser-\(account.id)"
        writeExecutable(browser.script, to: path)
        return path
    }

    /// Rewrites installed wrappers so they pick up improvements from newer versions.
    static func refreshInstalledWrappers() {
        if wrapperInstalled { installWrapper() }
        if FileManager.default.fileExists(atPath: vscodeWrapper) { installVSCodeWrapper() }
    }

    static let zshrcLine = "export PATH=\"$HOME/.claude-companion/bin:$PATH\"  # Claude Companion"

    static var wrapperInstalled: Bool { FileManager.default.fileExists(atPath: Paths.wrapper) }

    static var pathConfigured: Bool {
        let rc = Paths.home + "/.zshrc"
        return (try? String(contentsOfFile: rc, encoding: .utf8))?.contains(".claude-companion/bin") == true
    }

    /// A `claude` wrapper that sets CLAUDE_CONFIG_DIR from the active account, then runs the real CLI.
    static func installWrapper() {
        Paths.ensureDir(Paths.binDir)
        let script = #"""
        #!/bin/sh
        # Generated by Claude Companion. Launches the real `claude` with the active account.
        # Set CLAUDE_CONFIG_DIR yourself to override; CLAUDE_COMPANION_BYPASS=1 skips switching.
        SELF_DIR="$HOME/.claude-companion/bin"
        REAL=""
        OLDIFS="$IFS"; IFS=:
        for d in $PATH; do
          case "$d" in "$SELF_DIR"|"$SELF_DIR/") continue ;; esac
          if [ -x "$d/claude" ]; then REAL="$d/claude"; break; fi
        done
        IFS="$OLDIFS"
        if [ -z "$REAL" ]; then echo "claude-companion: real 'claude' not found in PATH" >&2; exit 127; fi
        if [ -z "$CLAUDE_COMPANION_BYPASS" ] && [ -z "$CLAUDE_CONFIG_DIR" ]; then
        \#(chooseAccountShell)
        \#(reminderShell)
          remind "$@"
        \#(applyAccountShell)
        fi
        exec "$REAL" "$@"
        """#
        writeExecutable(script, to: Paths.wrapper)
    }

    // MARK: VS Code extension

    static let vscodeWrapper = Paths.binDir + "/claude-vscode-wrapper"
    static let vscodeKey = "claudeCode.claudeProcessWrapper"

    /// User settings for VS Code and VS Code-based editors that run the Claude Code extension.
    static var editorSettingsFiles: [(name: String, path: String)] {
        let base = Paths.home + "/Library/Application Support"
        return [("VS Code", base + "/Code/User/settings.json"),
                ("VS Code Insiders", base + "/Code - Insiders/User/settings.json"),
                ("Cursor", base + "/Cursor/User/settings.json"),
                ("Windsurf", base + "/Windsurf/User/settings.json")]
            .filter { FileManager.default.fileExists(atPath: (($0.1 as NSString).deletingLastPathComponent)) }
    }

    static func vscodeConfigured(_ path: String) -> Bool {
        guard let s = try? String(contentsOfFile: path, encoding: .utf8) else { return false }
        return s.contains(vscodeKey) && s.contains("claude-vscode-wrapper")
    }

    /// The extension runs `<wrapper> <bundled claude binary> <args…>`; we only add CLAUDE_CONFIG_DIR.
    static func installVSCodeWrapper() {
        Paths.ensureDir(Paths.binDir)
        let script = #"""
        #!/bin/sh
        # Generated by Claude Companion. Used by the VS Code extension (claudeCode.claudeProcessWrapper).
        # The extension calls: <this script> <claude binary> <args...>
        if [ -z "$CLAUDE_COMPANION_BYPASS" ] && [ -z "$CLAUDE_CONFIG_DIR" ]; then
        \#(chooseAccountShell)
        \#(applyAccountShell)
        fi
        exec "$@"
        """#
        writeExecutable(script, to: vscodeWrapper)
    }

    /// Sets the extension's process wrapper with a text edit, so comments and formatting survive.
    static func configureVSCode(_ path: String) throws {
        installVSCodeWrapper()
        var s = (try? String(contentsOfFile: path, encoding: .utf8)) ?? "{\n}\n"
        if s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { s = "{\n}\n" }
        let line = "\"\(vscodeKey)\": \"\(vscodeWrapper)\""
        let pattern = "\"" + NSRegularExpression.escapedPattern(for: vscodeKey) + "\"\\s*:\\s*\"[^\"]*\""
        if let r = s.range(of: pattern, options: .regularExpression) {
            s.replaceSubrange(r, with: line)
        } else if let brace = s.firstIndex(of: "{") {
            let rest = s[s.index(after: brace)...]
            let isEmptyObject = rest.trimmingCharacters(in: .whitespacesAndNewlines).hasPrefix("}")
            s.insert(contentsOf: "\n    " + line + (isEmptyObject ? "\n" : ","), at: s.index(after: brace))
        } else {
            throw IntegrationError.invalidSettings(path)
        }
        let backup = path + ".companion-backup"
        if FileManager.default.fileExists(atPath: path), !FileManager.default.fileExists(atPath: backup) {
            try? FileManager.default.copyItem(atPath: path, toPath: backup)
        }
        try s.write(toFile: path, atomically: true, encoding: .utf8)
    }

    static func unconfigureVSCode(_ path: String) throws {
        guard var s = try? String(contentsOfFile: path, encoding: .utf8) else { return }
        let pattern = "\\n?[ \\t]*\"" + NSRegularExpression.escapedPattern(for: vscodeKey) + "\"\\s*:\\s*\"[^\"]*claude-vscode-wrapper\"[ \\t]*,?"
        guard let r = s.range(of: pattern, options: .regularExpression) else { return }
        s.removeSubrange(r)
        // If it was the last entry, drop a now-dangling comma before the closing brace.
        s = s.replacingOccurrences(of: #",(\s*)\}\s*$"#, with: "$1}\n", options: .regularExpression)
        try s.write(toFile: path, atomically: true, encoding: .utf8)
    }

    static func addToZshrc() throws {
        let rc = Paths.home + "/.zshrc"
        var contents = (try? String(contentsOfFile: rc, encoding: .utf8)) ?? ""
        if contents.contains(".claude-companion/bin") { return }
        if !contents.isEmpty && !contents.hasSuffix("\n") { contents += "\n" }
        contents += "\n" + zshrcLine + "\n"
        try contents.write(toFile: rc, atomically: true, encoding: .utf8)
    }

    /// Opens Terminal running Claude Code under this account so the user can /login.
    static func openLoginTerminal(for account: Account) {
        Paths.ensureDir(account.expandedConfigDir)
        let quoted = "'" + account.expandedConfigDir.replacingOccurrences(of: "'", with: "'\\''") + "'"
        var env = account.isDefaultDir ? "unset CLAUDE_CONFIG_DIR" : "export CLAUDE_CONFIG_DIR=\(quoted)"
        if let browser = browserScript(for: account) {
            env += "\nexport BROWSER='" + browser.replacingOccurrences(of: "'", with: "'\\''") + "'"
        }
        // A .command file doesn't load ~/.zshrc, where many people put Claude Code on their PATH
        // (npm, nvm, conda…), so use the full path we found.
        let launch: String
        if let claude = findClaude() {
            launch = "'" + claude.replacingOccurrences(of: "'", with: "'\\''") + "'"
        } else {
            launch = """
            echo "Claude Code wasn't found on this Mac (not in the usual places, your shell's PATH,"
            echo "or the VS Code / Cursor extension). Install it from"
            echo "https://docs.anthropic.com/en/docs/claude-code, then click Log in… again."
            """
        }
        let script = """
        #!/bin/zsh
        \(env)
        export CLAUDE_COMPANION_BYPASS=1
        echo "Claude Companion — config dir: ${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
        echo "Type /login inside Claude to sign in to this account."
        echo
        \(launch)
        """
        let path = Paths.companionDir + "/login-\(account.id).command"
        writeExecutable(script, to: path)
        NSWorkspace.shared.open(URL(fileURLWithPath: path))
    }

    /// Finds the real Claude Code executable: common install locations first, then the PATH of the
    /// user's interactive shell (which loads ~/.zshrc). Our own `claude` wrapper is skipped.
    static func findClaude(checkCommonLocations: Bool = true, checkShell: Bool = true) -> String? {
        let fm = FileManager.default
        let h = Paths.home
        var candidates = [h + "/.local/bin/claude", h + "/.claude/local/claude", "/opt/homebrew/bin/claude",
                          "/usr/local/bin/claude", h + "/.npm-global/bin/claude", h + "/.bun/bin/claude",
                          h + "/.volta/bin/claude"]
        if let versions = try? fm.contentsOfDirectory(atPath: h + "/.nvm/versions/node") {
            candidates += versions.sorted().reversed().map { h + "/.nvm/versions/node/\($0)/bin/claude" }
        }
        if checkCommonLocations, let found = candidates.first(where: { fm.isExecutableFile(atPath: $0) }) { return found }

        if checkShell, let found = claudeOnShellPath() { return found }
        // Last resort: the copy bundled with the Claude Code extension (people who only use it in their editor).
        return bundledEditorClaude()
    }

    /// The newest `claude` shipped inside the Claude Code extension of VS Code, Insiders, Cursor or Windsurf.
    static func bundledEditorClaude() -> String? {
        let fm = FileManager.default
        var found: [(version: [Int], path: String)] = []
        for editor in [".vscode", ".vscode-insiders", ".cursor", ".windsurf"] {
            let dir = Paths.home + "/\(editor)/extensions"
            for name in (try? fm.contentsOfDirectory(atPath: dir)) ?? [] where name.hasPrefix("anthropic.claude-code-") {
                let path = "\(dir)/\(name)/resources/native-binary/claude"
                guard fm.isExecutableFile(atPath: path) else { continue }
                let version = name.dropFirst("anthropic.claude-code-".count).split(separator: "-").first?
                    .split(separator: ".").map { Int($0) ?? 0 } ?? []
                found.append((version, path))
            }
        }
        return found.max { $0.version.lexicographicallyPrecedes($1.version) }?.path
    }

    private static func claudeOnShellPath() -> String? {
        let fm = FileManager.default
        // Ask the user's shell for its PATH, with their startup files loaded.
        let shell = ProcessInfo.processInfo.environment["SHELL"] ?? "/bin/zsh"
        let p = Process()
        p.executableURL = URL(fileURLWithPath: shell)
        p.arguments = ["-ilc", "printf '\\n__PATH__%s\\n' \"$PATH\""]
        let out = Pipe()
        p.standardOutput = out
        p.standardError = FileHandle.nullDevice
        p.standardInput = FileHandle.nullDevice
        guard (try? p.run()) != nil else { return nil }
        let deadline = Date().addingTimeInterval(6)
        while p.isRunning && Date() < deadline { Thread.sleep(forTimeInterval: 0.05) }
        if p.isRunning { p.terminate(); return nil }
        let text = String(decoding: out.fileHandleForReading.readDataToEndOfFile(), as: UTF8.self)
        guard let line = text.split(separator: "\n").last(where: { $0.hasPrefix("__PATH__") }) else { return nil }
        for dir in line.dropFirst("__PATH__".count).split(separator: ":") where !dir.isEmpty && String(dir) != Paths.binDir {
            let path = String(dir) + "/claude"
            if fm.isExecutableFile(atPath: path) { return path }
        }
        return nil
    }

    private static func writeExecutable(_ s: String, to path: String) {
        try? (s + "\n").write(toFile: path, atomically: true, encoding: .utf8)
        try? FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: path)
    }
}
